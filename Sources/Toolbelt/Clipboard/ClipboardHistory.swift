import AppKit

/// 클립보드 기록. 0.5초마다 changeCount를 보고 새 텍스트를 기록한다 (텍스트만, 최근 200개, 7일).
///   일반 텍스트 → 기록에 원문 (파일은 암호화)
///   비밀(민감 표시·제외 앱·키 형식) → 값은 보안 칩 키로 암호화, 기록에는 가린 미리보기. 꺼낼 때 Touch ID/암호 확인, 30초 뒤 클립보드에서 지움.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    static let maxItems = 200
    static let maxAge: TimeInterval = 7 * 24 * 3600
    static let secretClearDelay: TimeInterval = 30

    /// 비밀번호 관리자 등이 붙이는 표시 (nspasteboard.org 규약)
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// 여기서 복사한 것은 비밀로 취급한다
    static let defaultExcludedApps: [String] = [
        "com.apple.Passwords", "com.apple.keychainaccess",
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop",
        "com.lastpass.LastPass", "com.dashlane.Dashlane", "org.keepassxc.keepassxc",
    ]

    /// 설치돼 있지 않을 때 보여줄 이름
    nonisolated static let knownAppNames: [String: String] = [
        "com.apple.Passwords": "암호", "com.apple.keychainaccess": "키체인 접근",
        "com.1password.1password": "1Password", "com.agilebits.onepassword7": "1Password 7",
        "com.bitwarden.desktop": "Bitwarden", "com.lastpass.LastPass": "LastPass",
        "com.dashlane.Dashlane": "Dashlane", "org.keepassxc.keepassxc": "KeePassXC",
    ]

    @Published private(set) var items: [ClipItem] = []
    /// 비밀로 기억한 값의 지문 (기록이 지워져도 남는다)
    @Published private(set) var rememberedSecrets: Set<String> = []
    @Published private(set) var isEnabled: Bool
    @Published private(set) var isPaused = false
    @Published private(set) var excludedApps: [String]
    @Published private(set) var accessBehavior: NSPasteboard.AccessBehavior = .default
    @Published var notice: String?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    /// Toolbelt가 직접 쓴 변경은 기록하지 않는다
    private var ownChangeCount: Int?
    private var timer: Timer?
    private var lastPrune = Date()
    /// 접근 상태가 아직 '묻지 않음'일 때 macOS 허용 창을 한 번만 띄우기 위함
    private var askedOnce = false

    private init() {
        let defaults = UserDefaults.standard
        isEnabled = defaults.object(forKey: "clipboardEnabled") as? Bool ?? false   // 다른 사람에게는 기본 꺼짐
        excludedApps = defaults.stringArray(forKey: "clipboardExcludedApps") ?? Self.defaultExcludedApps
        lastChangeCount = NSPasteboard.general.changeCount
        let stored = ClipboardStore.load()
        items = stored.items
        rememberedSecrets = stored.rememberedSecrets
        prune()
    }

    // MARK: - 켜기/끄기

    func start() {
        refreshAccess()
        guard isEnabled, timer == nil else { return }
        lastChangeCount = pasteboard.changeCount   // 켜기 전에 복사된 것은 기록하지 않는다
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func setEnabled(_ on: Bool) {
        isEnabled = on
        UserDefaults.standard.set(on, forKey: "clipboardEnabled")
        if on {
            start()
        } else {
            timer?.invalidate()
            timer = nil
        }
    }

    func setPaused(_ paused: Bool) {
        isPaused = paused
        lastChangeCount = pasteboard.changeCount   // 일시정지 동안 복사된 것은 다시 켜도 기록하지 않는다
    }

    func refreshAccess() {
        accessBehavior = pasteboard.accessBehavior
    }

    var accessGranted: Bool { accessBehavior == .alwaysAllow }

    /// 권한 버튼: 아직 묻지 않았으면 클립보드를 한 번 읽어 macOS 허용 창을 띄우고(내용은 저장하지 않음),
    /// 이미 물었으면(묻기·거부) 시스템 설정의 해당 화면을 연다.
    func requestAccess() {
        refreshAccess()
        if accessBehavior == .default {
            _ = pasteboard.string(forType: .string)
            lastChangeCount = pasteboard.changeCount
            DispatchQueue.main.asyncAfter(deadline: .now() + 1) { [weak self] in self?.refreshAccess() }
        } else {
            NSWorkspace.shared.open(URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard")!)
        }
    }

    // MARK: - 감시

    private func poll() {
        if Date().timeIntervalSince(lastPrune) > 3600 {   // 새로 복사하지 않아도 7일 지난 항목은 지운다
            lastPrune = Date()
            prune()
        }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if count == ownChangeCount || isPaused { return }

        // macOS 26: '항상 허용'이 아니면 읽을 때마다 허용 창이 뜬다 → 처음 한 번만 묻고, 그 뒤에는 읽지 않고 안내만 한다
        refreshAccess()
        switch accessBehavior {
        case .alwaysAllow:
            break
        case .default where !askedOnce:
            askedOnce = true
        default:
            notice = "클립보드 접근이 '항상 허용'이 아니라 기록하지 않았습니다. 설정 → 권한에서 바꿔 주세요."
            return
        }

        let types = pasteboard.types ?? []
        if types.contains(Self.transientType) || types.contains(Self.autoGeneratedType) { return }
        // 실제 내용을 읽는 순간 macOS가 처음 한 번 클립보드 접근 허용을 묻는다
        guard let raw = pasteboard.string(forType: .string) else { refreshAccess(); return }
        refreshAccess()
        if accessBehavior == .alwaysAllow, notice?.hasPrefix("클립보드 접근이") == true { notice = nil }
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty, text.count <= 100_000 else { return }

        let app = NSWorkspace.shared.frontmostApplication
        let fromExcluded = app?.bundleIdentifier.map { excludedApps.contains($0) } ?? false
        let label: String?
        if types.contains(Self.concealedType) || fromExcluded {
            label = SecretDetector.detect(text) ?? "비밀번호"
        } else if let detected = SecretDetector.detect(text) {
            label = detected
        } else if !rememberedSecrets.isEmpty, let fp = ClipboardStore.fingerprint(text), rememberedSecrets.contains(fp) {
            label = "기억한 비밀"
        } else {
            label = nil
        }
        add(text, secretLabel: label, source: app?.localizedName)
    }

    private func add(_ text: String, secretLabel: String?, source: String?) {
        let id = UUID()
        if let secretLabel {
            // 같은 비밀을 연달아 복사한 경우는 한 번만
            if let first = items.first, first.isSecret, first.preview == SecretDetector.mask(text),
               Date().timeIntervalSince(first.date) < 5 { return }
            guard let sealed = ClipboardStore.sealSecret(text) else { return }
            items.insert(ClipItem(id: id, date: Date(), isSecret: true, text: nil,
                                  preview: SecretDetector.mask(text), label: secretLabel, source: source,
                                  sealedSecret: sealed), at: 0)
        } else {
            items.removeAll { !$0.isSecret && $0.text == text }   // 같은 내용은 맨 위로
            items.insert(ClipItem(id: id, date: Date(), isSecret: false, text: text,
                                  preview: Self.oneLine(text), label: nil, source: source), at: 0)
        }
        prune()
        persist()
    }

    // MARK: - 동작

    /// 항목을 다시 클립보드로. 비밀 항목은 Touch ID/암호 확인 후 복사하고 30초 뒤 지운다.
    func copy(_ item: ClipItem) {
        if item.isSecret {
            Task {
                guard let sealed = item.sealedSecret,
                      let secret = await ClipboardStore.openSecret(sealed, reason: "클립보드 기록의 비밀 항목을 복사합니다") else { return }
                write(secret, concealed: true)
                let written = ownChangeCount
                notice = "비밀 항목을 복사했습니다. \(Int(Self.secretClearDelay))초 뒤 클립보드에서 지웁니다."
                DispatchQueue.main.asyncAfter(deadline: .now() + Self.secretClearDelay) { [weak self] in
                    guard let self, self.pasteboard.changeCount == written else { return }
                    self.pasteboard.clearContents()
                    self.lastChangeCount = self.pasteboard.changeCount
                    self.notice = nil
                }
            }
        } else if let text = item.text {
            write(text, concealed: false)
            if let index = items.firstIndex(where: { $0.id == item.id }) {
                var moved = items.remove(at: index)
                moved.date = Date()
                items.insert(moved, at: 0)
                persist()
            }
        }
    }

    /// 비밀 항목의 값을 화면에 보여주기 위해 꺼낸다 (Touch ID/암호 확인)
    func reveal(_ item: ClipItem) async -> String? {
        guard item.isSecret else { return item.text }
        guard let sealed = item.sealedSecret else { return nil }
        return await ClipboardStore.openSecret(sealed, reason: "비밀 항목의 값을 화면에 표시합니다")
    }

    /// 일반 항목을 비밀로: 원문을 보안 칩 키로 암호화하고 기록에서는 가린다. 같은 값은 앞으로도 비밀로 저장한다.
    func markSecret(_ item: ClipItem) {
        guard !item.isSecret, let text = item.text,
              let index = items.firstIndex(where: { $0.id == item.id }),
              let sealed = ClipboardStore.sealSecret(text) else { return }
        items[index].isSecret = true
        items[index].sealedSecret = sealed
        items[index].text = nil
        items[index].preview = SecretDetector.mask(text)
        items[index].label = "직접 지정"
        if let fp = ClipboardStore.fingerprint(text) { rememberedSecrets.insert(fp) }
        // 같은 값이 기록에 일반 항목으로 더 있으면 그것도 비밀로
        for other in items where !other.isSecret && other.text == text { markSecret(other) }
        persist()
    }

    /// 비밀로 잘못 바꾼 항목을 되돌린다. 값이 보이게 되므로 Touch ID/암호를 확인한다. 기억한 지문도 지운다.
    func markNormal(_ item: ClipItem) {
        guard item.isSecret else { return }
        Task {
            guard let sealed = item.sealedSecret,
                  let text = await ClipboardStore.openSecret(sealed, reason: "비밀 항목을 일반 항목으로 바꿉니다"),
                  let index = items.firstIndex(where: { $0.id == item.id }) else { return }
            items[index].sealedSecret = nil
            items[index].isSecret = false
            items[index].text = text
            items[index].preview = Self.oneLine(text)
            items[index].label = nil
            if let fp = ClipboardStore.fingerprint(text) { rememberedSecrets.remove(fp) }
            persist()
        }
    }

    /// 비밀로 기억한 값을 모두 잊는다 (기록 항목은 그대로)
    func forgetRememberedSecrets() {
        rememberedSecrets = []
        persist()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        persist()
    }

    /// 기록을 모두 지운다. 비밀로 기억한 값은 남긴다 (따로 "모두 잊기").
    func clearAll() {
        items = []
        persist()
    }

    func addExcludedApp(_ bundleID: String) {
        guard !excludedApps.contains(bundleID) else { return }
        excludedApps.append(bundleID)
        UserDefaults.standard.set(excludedApps, forKey: "clipboardExcludedApps")
    }

    func removeExcludedApp(_ bundleID: String) {
        excludedApps.removeAll { $0 == bundleID }
        UserDefaults.standard.set(excludedApps, forKey: "clipboardExcludedApps")
    }

    // MARK: - 내부

    private func write(_ text: String, concealed: Bool) {
        pasteboard.clearContents()
        var types: [NSPasteboard.PasteboardType] = [.string]
        if concealed { types.append(Self.concealedType) }   // 다른 클립보드 앱도 기록하지 않도록
        pasteboard.declareTypes(types, owner: nil)
        pasteboard.setString(text, forType: .string)
        if concealed { pasteboard.setData(Data(), forType: Self.concealedType) }
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = ownChangeCount!
    }

    /// 200개·7일을 넘은 항목 삭제
    private func prune() {
        let cutoff = Date().addingTimeInterval(-Self.maxAge)
        let removed = items.enumerated().filter { $0.offset >= Self.maxItems || $0.element.date < cutoff }.map(\.element)
        guard !removed.isEmpty else { return }
        let ids = Set(removed.map(\.id))
        items.removeAll { ids.contains($0.id) }
        persist()
    }

    private func persist() {
        ClipboardStore.save(ClipboardData(items: items, rememberedSecrets: rememberedSecrets))
    }

    private static func oneLine(_ text: String) -> String {
        let line = text.split(whereSeparator: \.isNewline).first.map(String.init) ?? text
        return line.count > 200 ? String(line.prefix(200)) + "…" : line
    }
}
